
CREATE TABLE staff_healthcare_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    keycloak_user_id VARCHAR(100) NOT NULL,

    healthcare_unit_id BIGINT NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_staff_healthcare_unit
        FOREIGN KEY (healthcare_unit_id)
        REFERENCES healthcare_units(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_staff_healthcare_unit
        UNIQUE (keycloak_user_id, healthcare_unit_id),

    CONSTRAINT chk_staff_keycloak_user_id
        CHECK (LENGTH(TRIM(keycloak_user_id)) > 0)
);

CREATE INDEX idx_staff_healthcare_units_user
ON staff_healthcare_units (keycloak_user_id);

CREATE INDEX idx_staff_healthcare_units_unit
ON staff_healthcare_units (healthcare_unit_id);
