CREATE TABLE healthcare_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    city VARCHAR(100) NOT NULL,
    organization_code VARCHAR(50) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_healthcare_unit_name
        CHECK (LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_healthcare_unit_city
        CHECK (LENGTH(TRIM(city)) > 0)
);

CREATE INDEX idx_healthcare_units_city
ON healthcare_units (city);